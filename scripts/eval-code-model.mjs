/**
 * The one-component-swap harness for the local code model, on the gold plans -
 * docs/LOCAL-CODE-MODEL-PLAN.md §7.
 *
 * Phase R (reference, --build-reference): every gold plan is generated in full
 * by the REFERENCE provider (Gemini by default), installed, built and repaired
 * exactly as the server does it, then checked with Blueprint, the locator
 * detector and the runtime check. Projects passing everything are kept under
 * --reference=<dir>/<sessionId>/ with a manifest; the rest keep only their
 * manifest (passed:false) so a re-run skips them.
 *
 * Phase E (evaluation): for every backend/security component of every passing
 * reference project, the reference project is copied to a scratch root and ONLY
 * that component is regenerated by the CANDIDATE, with the reference's files as
 * context - the same context the reference component was written against.
 *
 *   A  first attempt: `npm run build` passes, Blueprint clean, locator clean,
 *      and the runtime check (D) passes for that component.
 *   B  the same after installBuildAndRepair's normal repair rounds, with the
 *      candidate doing the repairs.
 *   C  whole-project: the candidate writes EVERY backend+security component
 *      of the project, then a full build + the same three checks.
 *   D  reported on its own as well: the per-component runtime verdict in the
 *      A state (and the B state), since the ship bar requires it on every
 *      accepted component.
 *
 * node_modules: `npm install` for every one of ~94 swaps would dominate the
 * run (and hit the registry 94 times for identical lockfiles). The scratch
 * root gets a junction (Windows, no admin needed) or a directory symlink to
 * the reference project's node_modules, falling back to a recursive copy if
 * neither can be created. Nothing in a swap writes into node_modules, so
 * sharing it is safe; `npm install` inside installBuildAndRepair (metric B)
 * then sees an already-satisfied tree and is a quick no-op.
 *
 * Usage:
 *   node scripts/eval-code-model.mjs --build-reference [--reference-provider=gemini] [--reference=capture/code/gold-reference] [--limit=N]
 *   node scripts/eval-code-model.mjs --candidate=<local url>[,model=<name>] --out=training/eval/code/<name>.json [--domains=backend,security] [--limit=N]
 *   node scripts/eval-code-model.mjs --candidate=gemini --out=training/eval/code/gemini.json
 */
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { createLocalProvider } from '../dist/llm/local.js';
import { chooseProvider, createProvider } from '../dist/llm/select-provider.js';
import { loadEnvFile } from '../dist/llm/env-file.js';
import { validateProjectSchema } from '../dist/workflow/validate-project-schema.js';
import { generateAndVerifyProject, verifyGeneratedProject, writeProjectFiles } from '../dist/generate/verify-and-regenerate.js';
import { installBuildAndRepair, runCommand } from '../dist/generate/build-and-repair.js';
import { runRuntimeCheck, routeResultsFor } from '../dist/generate/runtime-check.js';
import { detectServiceLocatorEvasion } from '../dist/generate/detect-service-locator-evasion.js';
import { createComponentCodeGenerator } from '../dist/generate/component-codegen.js';
import { generateComponentFile } from '../dist/generate/generate-project.js';
import { componentTargetPath } from '../dist/generate/assemble.js';

loadEnvFile(process.cwd());

// ---- arguments ---------------------------------------------------------------

const args = process.argv.slice(2);
const argValue = (name) => {
  const found = args.find((a) => a === `--${name}` || a.startsWith(`--${name}=`));
  if (found === undefined) return undefined;
  return found.includes('=') ? found.slice(name.length + 3) : '';
};

const buildReference = argValue('build-reference') !== undefined;
const candidateArg = argValue('candidate');
const outPath = argValue('out');
const referenceDir = argValue('reference') ?? 'capture/code/gold-reference';
const goldPath = argValue('gold') ?? 'training/data/gold/gold.jsonl';
const limit = argValue('limit') ? Number(argValue('limit')) : Infinity;
const domainFilter = new Set((argValue('domains') ?? 'backend,security').split(',').map((d) => d.trim()));
const skipC = argValue('skip-c') !== undefined;

if (!buildReference && (!candidateArg || !outPath)) {
  console.error(
    'Usage:\n' +
      '  node scripts/eval-code-model.mjs --build-reference [--reference-provider=gemini] [--reference=dir] [--limit=N]\n' +
      '  node scripts/eval-code-model.mjs --candidate=<url>[,model=<name>]|gemini|anthropic|bluesminds --out=<file.json> [--domains=backend,security] [--limit=N] [--skip-c]',
  );
  process.exit(1);
}

// ---- providers ---------------------------------------------------------------

/** `<url>[,model=<name>]` -> local provider; a vendor name -> that vendor via the same env-driven factory the CLI uses. */
async function providerFor(spec) {
  if (/^https?:\/\//.test(spec)) {
    const [url, ...rest] = spec.split(',');
    const modelPart = rest.map((p) => p.trim()).find((p) => p.startsWith('model='));
    return createLocalProvider({ baseUrl: url.replace(/\/+$/, ''), ...(modelPart ? { model: modelPart.slice('model='.length) } : {}) });
  }
  const choice = chooseProvider({ ...process.env, VIBE_LLM_PROVIDER: spec });
  const provider = await createProvider(choice);
  if (provider === null) {
    console.error(`No API key found for provider "${choice.provider}" (expected ${choice.keyEnv}).`);
    process.exit(1);
  }
  return provider;
}

const nullCache = { get: () => undefined, set: () => {}, flush: async () => true, size: 0 };

// ---- gold plans (the test set - read here and only here) ---------------------

function loadGold() {
  const plans = [];
  for (const line of readFileSync(goldPath, 'utf8').split('\n')) {
    if (line.trim() === '') continue;
    const pair = JSON.parse(line);
    const validated = validateProjectSchema(pair.schema);
    if (!validated.ok) {
      console.error(`gold plan failed validateProjectSchema: ${JSON.stringify(validated.error).slice(0, 200)}`);
      process.exit(1);
    }
    plans.push(validated.value);
  }
  return plans;
}

// ---- checks shared by every phase --------------------------------------------

const IGNORED_ON_COPY = new Set(['node_modules', 'dist', '.vibe']);

/** Copies a project's source tree (never node_modules/dist/.vibe) to `target` and links node_modules there. */
function cloneProject(sourceRoot, target) {
  rmSync(target, { recursive: true, force: true });
  mkdirSync(target, { recursive: true });
  cpSync(sourceRoot, target, { recursive: true, filter: (src) => !IGNORED_ON_COPY.has(basename(src)) });
  const modules = join(sourceRoot, 'node_modules');
  if (!existsSync(modules)) return 'none';
  const link = join(target, 'node_modules');
  try {
    symlinkSync(resolve(modules), link, process.platform === 'win32' ? 'junction' : 'dir');
    return process.platform === 'win32' ? 'junction' : 'symlink';
  } catch {
    cpSync(modules, link, { recursive: true });
    return 'copy';
  }
}

/** Blueprint + locator + runtime, on whatever is on disk under `root`. */
async function checkProject(root, schema, files, buildOk) {
  const verified = buildOk ? await verifyGeneratedProject(root, schema) : null;
  const violations = verified === null ? [] : verified.ok ? verified.value : [{ kind: 'pipeline-error', message: verified.error.message }];
  const locator = detectServiceLocatorEvasion(files, schema.constraints);
  const runtime = buildOk ? await runRuntimeCheck(root, schema) : { started: false, routes: [], ok: false, serverOutput: 'build failed - server not started' };
  return { buildOk, violations, locator, runtime, perComponent: new Map(routeResultsFor(schema, runtime).map((e) => [e.targetPath, e])) };
}

function reasonsFor(check, targetPath) {
  const reasons = [];
  if (!check.buildOk) reasons.push('build-failed');
  if (check.violations.length > 0) reasons.push('blueprint-violation');
  if (check.locator.length > 0) reasons.push('service-locator-finding');
  if (check.buildOk && !check.runtime.started) reasons.push('runtime-not-started');
  if (targetPath === null) {
    if (check.runtime.started && !check.runtime.ok) reasons.push('runtime-route-failed');
  } else {
    const entry = check.perComponent.get(targetPath);
    if (check.runtime.started && entry !== undefined && !entry.passed) reasons.push('runtime-route-failed');
  }
  return reasons;
}

function evaluatedComponents(schema) {
  const list = [];
  // Same order generateProject writes them (database, backend, security, frontend) so metric C's context matches a fresh run.
  for (const domain of ['database', 'backend', 'security', 'frontend']) {
    if (!domainFilter.has(domain)) continue;
    for (const component of schema.domains[domain].components) list.push({ component, domain, targetPath: componentTargetPath(domain, component) });
  }
  return list;
}

// ---- phase R -------------------------------------------------------------------

async function buildReferenceProjects() {
  const provider = await providerFor(argValue('reference-provider') ?? 'gemini');
  console.log(`reference provider: ${provider.name}; output: ${referenceDir}`);
  let processed = 0;
  let kept = 0;
  for (const schema of loadGold()) {
    if (processed >= limit) break;
    const root = join(referenceDir, schema.sessionId);
    const manifestPath = join(root, 'manifest.json');
    if (existsSync(manifestPath)) {
      const existing = JSON.parse(readFileSync(manifestPath, 'utf8'));
      console.log(`-- ${schema.sessionId}: already ${existing.passed ? 'passing' : 'failed'}, skipped`);
      if (existing.passed) kept += 1;
      continue;
    }
    processed += 1;
    console.log(`-- ${schema.sessionId} (${schema.title})`);
    const generated = await generateAndVerifyProject(schema, { provider, cache: nullCache, skipCache: true, root });
    let manifest;
    if (!generated.ok) {
      manifest = { sessionId: schema.sessionId, passed: false, reasons: ['generation-failed'], error: generated.error };
    } else {
      const built = await installBuildAndRepair({ schema, llm: { provider, cache: nullCache }, root, files: generated.value.files });
      if (!built.ok) {
        manifest = { sessionId: schema.sessionId, passed: false, reasons: ['repair-failed'], error: built.error };
      } else {
        const buildOk = built.value.build.installOk && built.value.build.buildOk;
        const check = await checkProject(root, schema, built.value.files, buildOk);
        const reasons = reasonsFor(check, null);
        manifest = {
          sessionId: schema.sessionId,
          title: schema.title,
          passed: reasons.length === 0,
          reasons,
          provider: provider.name,
          files: built.value.files.map((f) => f.path),
          regenerations: [...generated.value.regenerationLog, ...built.value.regenerationLog].map((a) => ({ targetPath: a.targetPath, origin: a.origin, outcome: a.outcome })),
          build: built.value.build,
          runtime: { started: check.runtime.started, ok: check.runtime.ok, routes: check.runtime.routes },
          builtAt: new Date().toISOString(),
        };
      }
    }
    mkdirSync(root, { recursive: true });
    writeFileSync(join(root, 'schema.json'), JSON.stringify(schema, null, 2));
    writeFileSync(manifestPath, JSON.stringify(manifest, null, 2));
    if (manifest.passed) kept += 1;
    console.log(`   ${manifest.passed ? 'PASS' : 'FAIL ' + manifest.reasons.join(',')}`);
  }
  console.log(`\nreference projects passing: ${kept}`);
}

// ---- phase E -------------------------------------------------------------------

function loadReferenceProjects() {
  const projects = [];
  for (const schema of loadGold()) {
    const root = join(referenceDir, schema.sessionId);
    const manifestPath = join(root, 'manifest.json');
    if (!existsSync(manifestPath)) continue;
    const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
    if (!manifest.passed) continue;
    const files = manifest.files.map((path) => ({ path, contents: readFileSync(join(root, ...path.split('/')), 'utf8') }));
    projects.push({ schema, root, manifest, files });
  }
  return projects;
}

async function regenerateWith(provider, schema, entry, contextFiles) {
  const generator = createComponentCodeGenerator({ provider, cache: nullCache, skipCache: true });
  return generateComponentFile(generator, schema, entry.component, entry.domain, undefined, contextFiles);
}

async function evaluate() {
  const candidate = await providerFor(candidateArg);
  const evalName = basename(outPath, '.json');
  const workRoot = argValue('work') ?? join('capture/code/work', `eval-${evalName}`);
  const projects = loadReferenceProjects();
  console.log(`candidate: ${candidate.name}; reference projects: ${projects.length}; scratch: ${workRoot}`);

  const rows = [];
  const projectRows = [];
  let linkMode = null;
  let processed = 0;

  for (const { schema, root: referenceRoot, files: referenceFiles } of projects) {
    const components = evaluatedComponents(schema);
    for (const entry of components) {
      if (processed >= limit) break;
      processed += 1;
      const scratch = join(workRoot, schema.sessionId, entry.targetPath.replace(/[\\/]/g, '_'));
      linkMode = cloneProject(referenceRoot, scratch);
      const row = { sessionId: schema.sessionId, title: schema.title, component: entry.component.name, domain: entry.domain, targetPath: entry.targetPath, A: false, B: false, D_A: false, D_B: false, reasonsA: [], reasonsB: [], error: null };

      const regenerated = await regenerateWith(candidate, schema, entry, referenceFiles);
      if (!regenerated.ok) {
        row.error = regenerated.error.failure;
        row.reasonsA = ['generation-failed'];
        row.reasonsB = ['generation-failed'];
        rows.push(row);
        console.log(`!! ${schema.sessionId} ${entry.targetPath}: generation failed (${regenerated.error.failure.reason})`);
        continue;
      }
      let files = referenceFiles.map((f) => (f.path === entry.targetPath ? regenerated.value : f));
      await writeProjectFiles(scratch, [regenerated.value], false);
      row.candidateCode = regenerated.value.contents;

      // A: first attempt.
      const build = await runCommand('npm', ['run', 'build'], scratch);
      const checkA = await checkProject(scratch, schema, files, build.ok);
      row.reasonsA = reasonsFor(checkA, entry.targetPath);
      row.A = row.reasonsA.length === 0;
      row.D_A = checkA.perComponent.get(entry.targetPath)?.passed ?? false;
      row.buildOutputA = build.ok ? null : build.output;

      // B: with the candidate allowed the real repair rounds.
      if (row.A) {
        row.B = true;
        row.D_B = true;
        row.reasonsB = [];
      } else {
        const repaired = await installBuildAndRepair({ schema, llm: { provider: candidate, cache: nullCache }, root: scratch, files });
        if (!repaired.ok) {
          row.reasonsB = ['repair-failed'];
          row.error = repaired.error.failure;
        } else {
          files = repaired.value.files;
          const buildOkB = repaired.value.build.installOk && repaired.value.build.buildOk;
          const checkB = await checkProject(scratch, schema, files, buildOkB);
          row.reasonsB = reasonsFor(checkB, entry.targetPath);
          row.B = row.reasonsB.length === 0;
          row.D_B = checkB.perComponent.get(entry.targetPath)?.passed ?? false;
          row.repairRounds = repaired.value.regenerationLog.length;
          row.buildOutputB = buildOkB ? null : repaired.value.build.failureOutput ?? null;
        }
      }
      rows.push(row);
      console.log(`${row.A ? 'A ' : row.B ? ' B' : '!!'} ${schema.sessionId} ${entry.targetPath}${row.reasonsA.length ? '  A:' + row.reasonsA.join(',') : ''}${!row.B && row.reasonsB.length ? '  B:' + row.reasonsB.join(',') : ''}`);
    }
    if (processed >= limit) break;

    // C: the candidate writes every evaluated component, in generation order, each seeing the previous ones.
    if (skipC || components.length === 0) continue;
    const scratch = join(workRoot, schema.sessionId, '_whole-project');
    cloneProject(referenceRoot, scratch);
    let files = referenceFiles;
    let failure = null;
    for (const entry of components) {
      const regenerated = await regenerateWith(candidate, schema, entry, files);
      if (!regenerated.ok) {
        failure = { targetPath: entry.targetPath, failure: regenerated.error.failure };
        break;
      }
      files = files.map((f) => (f.path === entry.targetPath ? regenerated.value : f));
    }
    const projectRow = { sessionId: schema.sessionId, title: schema.title, components: components.length, C: false, reasons: [], error: failure };
    if (failure === null) {
      await writeProjectFiles(scratch, files, false);
      const build = await runCommand('npm', ['run', 'build'], scratch);
      const check = await checkProject(scratch, schema, files, build.ok);
      projectRow.reasons = reasonsFor(check, null);
      projectRow.C = projectRow.reasons.length === 0;
      projectRow.buildOutput = build.ok ? null : build.output;
      projectRow.routes = check.runtime.routes;
    } else {
      projectRow.reasons = ['generation-failed'];
    }
    projectRows.push(projectRow);
    console.log(`${projectRow.C ? 'C ' : '!!'} ${schema.sessionId} whole project${projectRow.reasons.length ? '  ' + projectRow.reasons.join(',') : ''}`);
  }

  const rate = (list, key) => (list.length === 0 ? null : list.filter((r) => r[key]).length / list.length);
  const byDomain = {};
  for (const domain of domainFilter) {
    const subset = rows.filter((r) => r.domain === domain);
    if (subset.length > 0) byDomain[domain] = { n: subset.length, A: rate(subset, 'A'), B: rate(subset, 'B'), D_A: rate(subset, 'D_A'), D_B: rate(subset, 'D_B') };
  }
  const report = {
    candidate: candidate.name,
    candidateModel: candidate.model,
    reference: referenceDir,
    referenceProjects: projects.length,
    nodeModulesSharing: linkMode,
    evaluatedAt: new Date().toISOString(),
    rates: { n: rows.length, A: rate(rows, 'A'), B: rate(rows, 'B'), D_A: rate(rows, 'D_A'), D_B: rate(rows, 'D_B'), projects: projectRows.length, C: rate(projectRows, 'C') },
    byDomain,
    rows,
    projects: projectRows,
  };
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, JSON.stringify(report, null, 2));

  const pct = (v) => (v === null ? '   -' : `${(v * 100).toFixed(1).padStart(5)}%`);
  console.log('\n--- results ---');
  console.log(`candidate: ${candidate.name}`);
  console.log(`${'scope'.padEnd(12)} ${'n'.padStart(4)}  ${'A'.padStart(7)} ${'B'.padStart(7)} ${'D(A)'.padStart(7)} ${'D(B)'.padStart(7)}`);
  console.log(`${'all'.padEnd(12)} ${String(rows.length).padStart(4)}  ${pct(report.rates.A)} ${pct(report.rates.B)} ${pct(report.rates.D_A)} ${pct(report.rates.D_B)}`);
  for (const [domain, r] of Object.entries(byDomain)) {
    console.log(`${domain.padEnd(12)} ${String(r.n).padStart(4)}  ${pct(r.A)} ${pct(r.B)} ${pct(r.D_A)} ${pct(r.D_B)}`);
  }
  console.log(`${'C (projects)'.padEnd(12)} ${String(projectRows.length).padStart(4)}  ${pct(report.rates.C)}`);
  console.log(`\nwritten to ${outPath}`);
}

if (buildReference) {
  await buildReferenceProjects();
} else {
  await evaluate();
}
